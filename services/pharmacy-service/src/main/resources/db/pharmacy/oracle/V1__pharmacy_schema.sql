-- pharmacy-service schema (Oracle). Mirrors db/migration/sqlserver/V1__pharmacy_schema.sql.
-- Stock can never go negative (CHECK), lots expire, Rx-only drugs need a prescription.

CREATE TABLE patient (
    id            NUMBER(19) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    synthetic_id  VARCHAR2(64 CHAR) NOT NULL CONSTRAINT uq_patient_synthetic UNIQUE,
    given_name    VARCHAR2(100 CHAR) NOT NULL,
    family_name   VARCHAR2(100 CHAR) NOT NULL,
    birth_date    DATE NOT NULL,
    sex           VARCHAR2(8 CHAR) NOT NULL,
    synthetic     BOOLEAN DEFAULT TRUE NOT NULL
);

CREATE TABLE app_user (
    id            NUMBER(19) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username      VARCHAR2(64 CHAR) NOT NULL CONSTRAINT uq_app_user_username UNIQUE,
    password_hash VARCHAR2(100 CHAR) NOT NULL,
    role          VARCHAR2(32 CHAR) NOT NULL,
    display_name  VARCHAR2(100 CHAR) NOT NULL,
    patient_id    NUMBER(19) REFERENCES patient (id),
    active        BOOLEAN DEFAULT TRUE NOT NULL
);

CREATE TABLE prescriber (
    id            NUMBER(19) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code          VARCHAR2(32 CHAR) NOT NULL CONSTRAINT uq_prescriber_code UNIQUE,
    name          VARCHAR2(200 CHAR) NOT NULL
);

CREATE TABLE drug (
    id            NUMBER(19) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    product_code  VARCHAR2(32 CHAR) NOT NULL CONSTRAINT uq_drug_product UNIQUE,
    ndc           VARCHAR2(16 CHAR),
    rxcui         VARCHAR2(16 CHAR) NOT NULL,
    name          VARCHAR2(200 CHAR) NOT NULL,
    strength      VARCHAR2(64 CHAR),
    dose_form     VARCHAR2(64 CHAR),
    rx_only       BOOLEAN NOT NULL,
    unit_price_cents NUMBER(10) NOT NULL CONSTRAINT ck_drug_price CHECK (unit_price_cents >= 0)
);

CREATE TABLE lot (
    id            NUMBER(19) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    drug_id       NUMBER(19) NOT NULL REFERENCES drug (id),
    lot_number    VARCHAR2(64 CHAR) NOT NULL,
    expiry_date   DATE NOT NULL,
    quantity      NUMBER(10) NOT NULL CONSTRAINT ck_lot_quantity CHECK (quantity >= 0),
    received_at   TIMESTAMP(6) NOT NULL,
    CONSTRAINT uq_lot UNIQUE (drug_id, lot_number)
);
CREATE INDEX ix_lot_fefo ON lot (drug_id, expiry_date);

CREATE TABLE prescription (
    id                 NUMBER(19) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    patient_id         NUMBER(19) NOT NULL REFERENCES patient (id),
    prescriber_id      NUMBER(19) NOT NULL REFERENCES prescriber (id),
    drug_id            NUMBER(19) NOT NULL REFERENCES drug (id),
    written_date       DATE NOT NULL,
    quantity           NUMBER(10) NOT NULL CONSTRAINT ck_rx_quantity CHECK (quantity > 0),
    remaining_quantity NUMBER(10) NOT NULL CONSTRAINT ck_rx_remaining CHECK (remaining_quantity >= 0),
    status             VARCHAR2(16 CHAR) NOT NULL
);

CREATE TABLE dispense_order (
    id              NUMBER(19) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    patient_id      NUMBER(19) NOT NULL REFERENCES patient (id),
    prescription_id NUMBER(19) REFERENCES prescription (id),
    drug_id         NUMBER(19) NOT NULL REFERENCES drug (id),
    quantity        NUMBER(10) NOT NULL CONSTRAINT ck_order_quantity CHECK (quantity > 0),
    total_cents     NUMBER(12) NOT NULL,
    pharmacist      VARCHAR2(64 CHAR) NOT NULL,
    created_at      TIMESTAMP(6) NOT NULL
);

CREATE TABLE dispense_line (
    id        NUMBER(19) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id  NUMBER(19) NOT NULL REFERENCES dispense_order (id),
    lot_id    NUMBER(19) NOT NULL REFERENCES lot (id),
    quantity  NUMBER(10) NOT NULL CONSTRAINT ck_line_quantity CHECK (quantity > 0)
);

CREATE TABLE side_effect_report (
    id                 NUMBER(19) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    patient_id         NUMBER(19) NOT NULL REFERENCES patient (id),
    drug_id            NUMBER(19) NOT NULL REFERENCES drug (id),
    reporter           VARCHAR2(64 CHAR) NOT NULL,
    narrative          VARCHAR2(4000 CHAR) NOT NULL,
    onset_date         DATE,
    status             VARCHAR2(24 CHAR) NOT NULL,
    external_report_id VARCHAR2(64 CHAR),
    created_at         TIMESTAMP(6) NOT NULL
);
