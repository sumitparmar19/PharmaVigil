-- intake-gateway schema (Oracle): one receipt per accepted submission, plus the transactional outbox that
-- carries report.received events to Kafka (relay in M8). Resends of the same payload are recognised by
-- its SHA-256 and never produce a second event.
CREATE TABLE intake_receipt (
    id                NUMBER(19) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    receipt_id        VARCHAR2(36 CHAR) NOT NULL CONSTRAINT uq_receipt_id UNIQUE,
    source            VARCHAR2(16 CHAR) NOT NULL,
    source_report_id  VARCHAR2(100 CHAR) NOT NULL,
    partner_reference VARCHAR2(100 CHAR),
    submitted_by      VARCHAR2(100 CHAR) NOT NULL,
    payload_sha256    VARCHAR2(64 CHAR) NOT NULL,
    follow_up         BOOLEAN NOT NULL,
    schema_checked    BOOLEAN NOT NULL,
    status            VARCHAR2(16 CHAR) NOT NULL,
    received_at       TIMESTAMP(6) NOT NULL,
    CONSTRAINT uq_receipt_payload UNIQUE (source, source_report_id, payload_sha256)
);
CREATE INDEX ix_receipt_report ON intake_receipt (source, source_report_id, id);

CREATE TABLE outbox_event (
    id              NUMBER(19) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    event_id        VARCHAR2(64 CHAR) NOT NULL CONSTRAINT uq_outbox_event UNIQUE,
    aggregate_type  VARCHAR2(32 CHAR) NOT NULL,
    aggregate_id    VARCHAR2(64 CHAR) NOT NULL,
    topic           VARCHAR2(64 CHAR) NOT NULL,
    payload         CLOB NOT NULL,
    created_at      TIMESTAMP(6) NOT NULL,
    published_at    TIMESTAMP(6),
    attempts        NUMBER(10) NOT NULL
);
CREATE INDEX ix_outbox_unpublished ON outbox_event (published_at, id);
