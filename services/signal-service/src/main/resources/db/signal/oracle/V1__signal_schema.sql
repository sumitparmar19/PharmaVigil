-- signal-service schema (Oracle): each load of the exported signal tables is a snapshot (scope, file hash, row
-- counts, evaluation summary); queries read the newest snapshot. Snapshots are kept, so an answer can always be
-- traced to the export it came from.
CREATE TABLE signal_snapshot (
    id             NUMBER(19) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    scope          VARCHAR2(200 CHAR) NOT NULL,
    source_sha256  VARCHAR2(64 CHAR) NOT NULL CONSTRAINT uq_snapshot_source UNIQUE,
    pairs          NUMBER(10) NOT NULL,
    with_sf        NUMBER(1) NOT NULL,
    evaluation     CLOB,
    loaded_at      TIMESTAMP(6) NOT NULL
);

CREATE TABLE drug_event_signal (
    snapshot_id   NUMBER(19) NOT NULL CONSTRAINT fk_signal_snapshot REFERENCES signal_snapshot (id),
    rxcui         VARCHAR2(16 CHAR) NOT NULL,
    ingredient    VARCHAR2(200 CHAR),
    pt            VARCHAR2(200 CHAR) NOT NULL,
    a             NUMBER(10) NOT NULL,
    n_drug        NUMBER(10),
    n_event       NUMBER(10),
    n_total       NUMBER(10),
    prr           BINARY_DOUBLE,
    prr_lo        BINARY_DOUBLE,
    prr_hi        BINARY_DOUBLE,
    ror           BINARY_DOUBLE,
    ror_lo        BINARY_DOUBLE,
    ror_hi        BINARY_DOUBLE,
    ic            BINARY_DOUBLE,
    ic025         BINARY_DOUBLE,
    ic975         BINARY_DOUBLE,
    ebgm          BINARY_DOUBLE,
    eb05          BINARY_DOUBLE,
    eb95          BINARY_DOUBLE,
    safetyformer  BINARY_DOUBLE,
    CONSTRAINT pk_drug_event_signal PRIMARY KEY (snapshot_id, rxcui, pt)
);
CREATE INDEX ix_signal_eb05 ON drug_event_signal (snapshot_id, eb05);

CREATE TABLE signal_trend (
    snapshot_id  NUMBER(19) NOT NULL CONSTRAINT fk_trend_snapshot REFERENCES signal_snapshot (id),
    rxcui        VARCHAR2(16 CHAR) NOT NULL,
    pt           VARCHAR2(200 CHAR) NOT NULL,
    year         NUMBER(4) NOT NULL,
    reports      NUMBER(10) NOT NULL,
    CONSTRAINT pk_signal_trend PRIMARY KEY (snapshot_id, rxcui, pt, year)
);
