// Outbox relay against a real database and broker: rows go out in id order with key and event-id header and
// are marked published; when Kafka is down nothing is lost, the attempt is counted and the row stays pending.
package io.pharmavigil.common.outbox;

import static org.assertj.core.api.Assertions.assertThat;

import java.nio.charset.StandardCharsets;
import java.sql.Timestamp;
import java.time.Clock;
import java.time.Duration;
import java.time.Instant;
import java.util.List;
import java.util.Map;
import java.util.UUID;

import org.apache.kafka.clients.producer.ProducerConfig;
import org.apache.kafka.common.serialization.StringSerializer;
import org.junit.jupiter.api.BeforeAll;
import org.junit.jupiter.api.Test;
import org.springframework.jdbc.core.JdbcTemplate;
import org.springframework.jdbc.datasource.DriverManagerDataSource;
import org.springframework.kafka.core.DefaultKafkaProducerFactory;
import org.springframework.kafka.core.KafkaTemplate;

import io.pharmavigil.common.testing.TestDatabases;
import io.pharmavigil.common.testing.TestKafka;

class OutboxRelayTest {

    static JdbcTemplate jdbc;

    @BeforeAll
    static void schema() {
        var db = TestDatabases.container();
        jdbc = new JdbcTemplate(new DriverManagerDataSource(db.getJdbcUrl(), db.getUsername(), db.getPassword()));
        boolean mssql = TestDatabases.engine().equals("mssql");
        jdbc.execute(mssql
                ? "CREATE TABLE outbox_event (id BIGINT IDENTITY(1,1) PRIMARY KEY, event_id VARCHAR(64) NOT NULL, "
                        + "aggregate_type VARCHAR(32) NOT NULL, aggregate_id VARCHAR(64) NOT NULL, "
                        + "topic VARCHAR(64) NOT NULL, payload VARCHAR(MAX) NOT NULL, created_at DATETIME2(6) NOT NULL, "
                        + "published_at DATETIME2(6), attempts INT NOT NULL)"
                : "CREATE TABLE outbox_event (id NUMBER(19) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, "
                        + "event_id VARCHAR2(64) NOT NULL, aggregate_type VARCHAR2(32) NOT NULL, "
                        + "aggregate_id VARCHAR2(64) NOT NULL, topic VARCHAR2(64) NOT NULL, payload CLOB NOT NULL, "
                        + "created_at TIMESTAMP(6) NOT NULL, published_at TIMESTAMP(6), attempts NUMBER(10) NOT NULL)");
    }

    private static String insert(String topic, String key, String payload) {
        String id = UUID.randomUUID().toString();
        jdbc.update("INSERT INTO outbox_event (event_id, aggregate_type, aggregate_id, topic, payload, created_at, "
                + "attempts) VALUES (?, 'test', ?, ?, ?, ?, 0)", id, key, topic, payload, Timestamp.from(Instant.now()));
        return id;
    }

    private static KafkaTemplate<String, String> template(String bootstrap) {
        return new KafkaTemplate<>(new DefaultKafkaProducerFactory<>(Map.of(
                ProducerConfig.BOOTSTRAP_SERVERS_CONFIG, bootstrap, ProducerConfig.MAX_BLOCK_MS_CONFIG, 2000,
                ProducerConfig.DELIVERY_TIMEOUT_MS_CONFIG, 3000, ProducerConfig.REQUEST_TIMEOUT_MS_CONFIG, 2000),
                new StringSerializer(), new StringSerializer()));
    }

    @Test
    void publishesInOrderAndMarksRows() {
        jdbc.update("UPDATE outbox_event SET published_at = ? WHERE published_at IS NULL", Timestamp.from(Instant.now()));
        String topic = "relay-test-" + UUID.randomUUID();
        String e1 = insert(topic, "case-1", "{\"n\":1}");
        insert(topic, "case-1", "{\"n\":2}");
        insert(topic, "case-1", "{\"n\":3}");
        OutboxRelay relay = new OutboxRelay(jdbc, template(TestKafka.bootstrap()), Clock.systemUTC(),
                Duration.ofSeconds(1), 100, Duration.ofSeconds(20));
        assertThat(relay.publishPending()).isEqualTo(3);
        assertThat(relay.backlog()).isZero();
        assertThat(relay.publishPending()).isZero();

        try (var consumer = TestKafka.consumer(List.of(topic))) {
            var records = TestKafka.poll(consumer, 3, Duration.ofSeconds(30));
            assertThat(records).extracting(r -> r.value()).containsExactly("{\"n\":1}", "{\"n\":2}", "{\"n\":3}");
            assertThat(records.get(0).key()).isEqualTo("case-1");
            assertThat(new String(records.get(0).headers().lastHeader(OutboxRelay.EVENT_ID_HEADER).value(),
                    StandardCharsets.UTF_8)).isEqualTo(e1);
        }
    }

    @Test
    void brokerDownKeepsRowsPendingAndCountsAttempts() {
        jdbc.update("UPDATE outbox_event SET published_at = ? WHERE published_at IS NULL", Timestamp.from(Instant.now()));
        String id = insert("relay-down", "k", "{}");
        OutboxRelay relay = new OutboxRelay(jdbc, template("127.0.0.1:1"), Clock.systemUTC(), Duration.ofSeconds(1),
                10, Duration.ofSeconds(5));
        assertThat(relay.publishPending()).isZero();
        assertThat(relay.backlog()).isEqualTo(1);
        assertThat(jdbc.queryForObject("SELECT attempts FROM outbox_event WHERE event_id = ?", Integer.class, id))
                .isEqualTo(1);
        relay.start();
        assertThat(relay.isRunning()).isTrue();
        relay.stop();
        assertThat(relay.isRunning()).isFalse();
        jdbc.update("UPDATE outbox_event SET published_at = ? WHERE event_id = ?", Timestamp.from(Instant.now()), id);
    }
}
