-- Submission history (M8): one row per status change of an E2B(R3) submission (QUEUED, ACK, NACK), append-only,
-- so a case that was NACKed, corrected and resubmitted keeps its whole trail.
CREATE TABLE submission_event (
    id               NUMBER(19) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    case_id          NUMBER(19) NOT NULL CONSTRAINT fk_submission_case REFERENCES safety_case (id),
    version_no       NUMBER(10) NOT NULL,
    safety_report_id VARCHAR2(100 CHAR) NOT NULL,
    message_id       VARCHAR2(100 CHAR),
    status           VARCHAR2(16 CHAR) NOT NULL,
    reason           VARCHAR2(2000 CHAR),
    occurred_at      TIMESTAMP(6) NOT NULL
);
CREATE INDEX ix_submission_case ON submission_event (case_id, id);
