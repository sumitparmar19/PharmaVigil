-- case-service schema (Oracle). Mirrors db/migration/sqlserver/V1__case_schema.sql.
-- A case head points at append-only versions; every change is audited; AI suggestions and reviewer
-- choices are kept side by side (review_decision doubles as the feedback table for retraining).

CREATE TABLE safety_case (
    id                  NUMBER(19) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    case_number         VARCHAR2(32 CHAR) NOT NULL CONSTRAINT uq_case_number UNIQUE,
    source              VARCHAR2(16 CHAR) NOT NULL,
    source_report_id    VARCHAR2(100 CHAR) NOT NULL,
    status              VARCHAR2(24 CHAR) NOT NULL,
    seriousness         VARCHAR2(16 CHAR) NOT NULL,
    serious_score       NUMBER(6,5),
    received_date       DATE NOT NULL,
    due_date            DATE NOT NULL,
    current_version     NUMBER(10) NOT NULL,
    duplicate_of_id     NUMBER(19) REFERENCES safety_case (id),
    duplicate_score     NUMBER(6,5),
    lock_version        NUMBER(10) NOT NULL,
    created_at          TIMESTAMP(6) NOT NULL,
    updated_at          TIMESTAMP(6) NOT NULL,
    CONSTRAINT uq_case_source UNIQUE (source, source_report_id)
);
CREATE INDEX ix_case_queue ON safety_case (status, due_date);

CREATE TABLE case_version (
    id              NUMBER(19) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    case_id         NUMBER(19) NOT NULL REFERENCES safety_case (id),
    version_no      NUMBER(10) NOT NULL,
    created_by      VARCHAR2(64 CHAR) NOT NULL,
    created_at      TIMESTAMP(6) NOT NULL,
    reason          VARCHAR2(200 CHAR) NOT NULL,
    patient_age     NUMBER(5,1),
    patient_sex     VARCHAR2(8 CHAR),
    reporter_type   VARCHAR2(32 CHAR),
    country         VARCHAR2(2 CHAR),
    onset_date      DATE,
    reported_text   VARCHAR2(4000 CHAR) NOT NULL,
    serious_criteria VARCHAR2(200 CHAR),
    CONSTRAINT uq_case_version UNIQUE (case_id, version_no)
);

CREATE TABLE case_drug (
    id          NUMBER(19) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    version_id  NUMBER(19) NOT NULL REFERENCES case_version (id),
    rxcui       VARCHAR2(16 CHAR),
    drug_name   VARCHAR2(200 CHAR) NOT NULL,
    role        VARCHAR2(4 CHAR) NOT NULL,
    dose_text   VARCHAR2(200 CHAR),
    route       VARCHAR2(64 CHAR)
);

CREATE TABLE case_reaction (
    id             NUMBER(19) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    version_id     NUMBER(19) NOT NULL REFERENCES case_version (id),
    reported_term  VARCHAR2(400 CHAR) NOT NULL,
    pt             VARCHAR2(200 CHAR),
    code_source    VARCHAR2(16 CHAR) NOT NULL,
    model_name     VARCHAR2(100 CHAR),
    model_version  VARCHAR2(64 CHAR),
    model_score    NUMBER(6,5)
);

CREATE TABLE narrative (
    id           NUMBER(19) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    case_id      NUMBER(19) NOT NULL REFERENCES safety_case (id),
    version_no   NUMBER(10) NOT NULL,
    body         VARCHAR2(4000 CHAR) NOT NULL,
    source       VARCHAR2(16 CHAR) NOT NULL,
    model_name   VARCHAR2(100 CHAR),
    created_by   VARCHAR2(64 CHAR) NOT NULL,
    created_at   TIMESTAMP(6) NOT NULL,
    approved_by  VARCHAR2(64 CHAR),
    approved_at  TIMESTAMP(6)
);

CREATE TABLE audit_event (
    id        NUMBER(19) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    case_id   NUMBER(19) NOT NULL REFERENCES safety_case (id),
    actor     VARCHAR2(64 CHAR) NOT NULL,
    action    VARCHAR2(48 CHAR) NOT NULL,
    detail    VARCHAR2(2000 CHAR),
    occurred_at TIMESTAMP(6) NOT NULL
);
CREATE INDEX ix_audit_case ON audit_event (case_id, occurred_at);

CREATE TABLE review_decision (
    id               NUMBER(19) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    case_id          NUMBER(19) NOT NULL REFERENCES safety_case (id),
    version_no       NUMBER(10) NOT NULL,
    reviewer         VARCHAR2(64 CHAR) NOT NULL,
    field            VARCHAR2(24 CHAR) NOT NULL,
    item_ref         VARCHAR2(400 CHAR),
    model_suggestion VARCHAR2(400 CHAR),
    model_name       VARCHAR2(100 CHAR),
    model_version    VARCHAR2(64 CHAR),
    model_score      NUMBER(6,5),
    final_value      VARCHAR2(400 CHAR),
    accepted         BOOLEAN NOT NULL,
    decided_at       TIMESTAMP(6) NOT NULL
);

CREATE TABLE processed_event (
    event_id      VARCHAR2(64 CHAR) NOT NULL,
    consumer      VARCHAR2(64 CHAR) NOT NULL,
    processed_at  TIMESTAMP(6) NOT NULL,
    CONSTRAINT pk_processed_event PRIMARY KEY (event_id, consumer)
);

CREATE TABLE outbox_event (
    id              NUMBER(19) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    event_id        VARCHAR2(64 CHAR) NOT NULL CONSTRAINT uq_outbox_event UNIQUE,
    aggregate_type  VARCHAR2(32 CHAR) NOT NULL,
    aggregate_id    VARCHAR2(64 CHAR) NOT NULL,
    topic           VARCHAR2(64 CHAR) NOT NULL,
    payload         CLOB NOT NULL,
    created_at      TIMESTAMP(6) NOT NULL,
    published_at    TIMESTAMP(6),
    attempts        NUMBER(10) NOT NULL
);
CREATE INDEX ix_outbox_unpublished ON outbox_event (published_at, id);
