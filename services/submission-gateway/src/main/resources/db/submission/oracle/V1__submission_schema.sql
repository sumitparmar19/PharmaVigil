-- submission-gateway schema (Oracle): one row per JMS message sent to the regulator with its latest
-- acknowledgement, plus processed-event and outbox tables for idempotent Kafka consumption and publishing.
CREATE TABLE submission_message (
    id               NUMBER(19) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    message_id       VARCHAR2(100 CHAR) NOT NULL CONSTRAINT uq_submission_message UNIQUE,
    case_id          NUMBER(19) NOT NULL,
    case_number      VARCHAR2(40 CHAR) NOT NULL,
    version_no       NUMBER(10) NOT NULL,
    safety_report_id VARCHAR2(100 CHAR) NOT NULL,
    status           VARCHAR2(16 CHAR) NOT NULL,
    reason           VARCHAR2(2000 CHAR),
    queued_at        TIMESTAMP(6) NOT NULL,
    answered_at      TIMESTAMP(6)
);

CREATE TABLE processed_event (
    event_id      VARCHAR2(64 CHAR) NOT NULL,
    consumer      VARCHAR2(64 CHAR) NOT NULL,
    processed_at  TIMESTAMP(6) NOT NULL,
    CONSTRAINT pk_processed_event PRIMARY KEY (event_id, consumer)
);

CREATE TABLE outbox_event (
    id              NUMBER(19) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    event_id        VARCHAR2(64 CHAR) NOT NULL CONSTRAINT uq_outbox_event UNIQUE,
    aggregate_type  VARCHAR2(32 CHAR) NOT NULL,
    aggregate_id    VARCHAR2(64 CHAR) NOT NULL,
    topic           VARCHAR2(64 CHAR) NOT NULL,
    payload         CLOB NOT NULL,
    created_at      TIMESTAMP(6) NOT NULL,
    published_at    TIMESTAMP(6),
    attempts        NUMBER(10) NOT NULL
);
CREATE INDEX ix_outbox_unpublished ON outbox_event (published_at, id);
